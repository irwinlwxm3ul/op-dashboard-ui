//   categories it does not use to the same text, so every locale shares one key set.
// * Keys reflect game codes where possible (item.<ItemId>, vehicle.<VehicleType>,
//   controls.action.<KeyAction>, mp.status.<LobbyStatus>, error.<LobbyErrorCode>, ...), so callers
//   can build them from typed values.
